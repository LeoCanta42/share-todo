-- ==============================================================================
-- ShareToDo - Complete Database Schema with Authentication & RLS & Sharing
--
-- WHERE TO RUN
--   Supabase Dashboard -> SQL Editor.
--
-- THIS FILE IS IDEMPOTENT AND IS ALSO THE MIGRATION
--   Every statement is guarded (IF NOT EXISTS / OR REPLACE / DROP ... IF EXISTS),
--   so re-running the whole file on an existing database is safe: it creates what
--   is missing, refreshes every policy and function, and never drops your rows.
--   Applying an update == re-running this file.
--
-- WHAT IS IN HERE
--   1. tables ........ todos (activities), notes, todo_shares, profiles
--   2. approval ...... a signed-up user is "pending" until an admin approves them;
--                      while pending, RLS returns no rows for them
--   3. sharing ....... group-scoped: one share row = one (person, group) grant,
--                      and it governs both todos and notes of that group
--      group_name IS NULL        -> the whole list is shared
--      group_name IS NOT NULL    -> only that subgroup is shared
--   4. admin ......... SECURITY DEFINER functions an admin calls from the app to
--                      list/approve/delete users and reset their passwords
--
-- GRANTING YOURSELF ADMIN (run separately, after this file)
--   update public.profiles set is_admin = true, approved = true
--   where lower(email) = lower('you@example.com');
--   (there is deliberately no API that can grant admin rights)
-- ==============================================================================

create extension if not exists pgcrypto with schema extensions;


