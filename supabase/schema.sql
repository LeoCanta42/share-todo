-- A user reads their own row and nothing else. Read-only on purpose: there is NO
-- insert/update/delete policy here, so `approved`/`is_admin` cannot be set from the
-- client with the publishable key. Only the section 4 functions can change them.
CREATE POLICY "Users can view own profile"
ON public.profiles FOR SELECT
TO authenticated
USING (auth.uid() = id);

CREATE POLICY "Admins can view all profiles"
ON public.profiles FOR SELECT
TO authenticated
USING (public.is_admin(auth.uid()));


-- ==============================================================================
-- 6. PRIVILEGI TABELLARI (GRANT)
-- Nota: una tabella creata tramite script / SQL Editor può non ricevere i GRANT
-- automatici che la Dashboard assegna alle tabelle create dall'interfaccia.
-- Senza questi GRANT il client autenticato riceve:
--   permission denied for table todo_shares   (SQLSTATE 42501)
-- anche quando la query riguarda soltanto 'todos': le policy RLS sopra eseguono
-- una sottoquery su public.todo_shares, valutata con i privilegi del chiamante.
-- I GRANT decidono se la tabella è accessibile; le policy RLS decidono QUALI righe
-- sono visibili. Servono entrambi.
-- ==============================================================================

GRANT USAGE ON SCHEMA public TO anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.todos       TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.notes       TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.todo_shares TO anon, authenticated;
-- profiles: read-only, and RLS restricts it to your own row (or everything, for admins).
GRANT SELECT ON public.profiles TO authenticated;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

-- Functions default to EXECUTE for PUBLIC; take it back and hand it out narrowly.
REVOKE ALL ON FUNCTION public.is_admin(UUID) FROM PUBLIC, anon;
