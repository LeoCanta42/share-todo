-- --------------------------------------------------------------- 5.1 todos
DROP POLICY IF EXISTS "Users can view own or shared todos" ON public.todos;
DROP POLICY IF EXISTS "Users can insert own todos" ON public.todos;
DROP POLICY IF EXISTS "Users can update own or shared todos" ON public.todos;
DROP POLICY IF EXISTS "Users can delete own or shared todos" ON public.todos;

-- SELECT: l'utente può vedere i propri task OPPURE quelli di un gruppo condiviso
-- con lui. Il confronto sul gruppo è quello che rende la condivisione "per gruppo":
--   s.group_name IS NULL            -> tutta la lista
--   s.group_name = <gruppo del todo> -> solo quel sottogruppo
-- `is_approved` is the gate: a pending account matches nothing at all.
CREATE POLICY "Users can view own or shared todos"
ON public.todos FOR SELECT
TO authenticated
USING (
  public.is_approved(auth.uid())
  AND (
    auth.uid() = user_id
    OR EXISTS (
      SELECT 1 FROM public.todo_shares s
      WHERE s.owner_id = todos.user_id
        AND (
          s.shared_with_id = auth.uid()
          OR LOWER(s.shared_with_email) = LOWER(auth.jwt() ->> 'email')
        )
        AND (s.group_name IS NULL OR s.group_name = COALESCE(todos.group_name, 'Generale'))
    )
  )
);

-- INSERT: l'utente può inserire solo task con il proprio user_id
CREATE POLICY "Users can insert own todos"
ON public.todos FOR INSERT
TO authenticated
WITH CHECK (
  public.is_approved(auth.uid())
  AND auth.uid() = user_id
);

-- UPDATE: l'utente può modificare i propri task OPPURE quelli di un gruppo
-- condiviso con permesso 'edit'
CREATE POLICY "Users can update own or shared todos"
ON public.todos FOR UPDATE
TO authenticated
USING (
  public.is_approved(auth.uid())
  AND (
    auth.uid() = user_id
    OR EXISTS (
      SELECT 1 FROM public.todo_shares s
      WHERE s.owner_id = todos.user_id
        AND (
          s.shared_with_id = auth.uid()
          OR LOWER(s.shared_with_email) = LOWER(auth.jwt() ->> 'email')
        )
        AND (s.group_name IS NULL OR s.group_name = COALESCE(todos.group_name, 'Generale'))
        AND s.permission = 'edit'
    )
  )
);

-- DELETE: l'utente può eliminare i propri task OPPURE quelli di un gruppo
-- condiviso con permesso 'edit'
CREATE POLICY "Users can delete own or shared todos"
ON public.todos FOR DELETE
TO authenticated
USING (
  public.is_approved(auth.uid())
  AND (
    auth.uid() = user_id
    OR EXISTS (
      SELECT 1 FROM public.todo_shares s
      WHERE s.owner_id = todos.user_id
        AND (
          s.shared_with_id = auth.uid()
          OR LOWER(s.shared_with_email) = LOWER(auth.jwt() ->> 'email')
        )
        AND (s.group_name IS NULL OR s.group_name = COALESCE(todos.group_name, 'Generale'))
        AND s.permission = 'edit'
    )
  )
);


